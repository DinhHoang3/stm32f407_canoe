int main(void) 
{
    uint8_t msg[50] = "Hello from STM32F4\r\n";
    uint8_t Retval = 0;

    Rcc_Init();
		SysTick_DelayInit();
    USART3_Init(4800);
    USART3_EnableRxIT();
		Gpio_InitLed();
    
		Gpio_GreenLed_On();
    USART3_SendBuffer((uint8_t*)msg);
		
    while(1) 
		{
        Retval = USART3_ReadBuffer(msg, 30);
        if (Retval == 1) 
        {
          while(1){
            USART3_SendBuffer((uint8_t*)msg);
            Gpio_BlueLed_On();
            SysTick_Delay(500);
            Gpio_BlueLed_Off();
            SysTick_Delay(500);
            }
        }
    }
}


